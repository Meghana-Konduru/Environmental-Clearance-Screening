
"""
Shared state definition for the Environmental Clearance
Pre-Screening LangGraph workflow.
"""

from typing import Any, Dict, List, TypedDict


class ScreeningState(TypedDict, total=False):
    """
    Shared state passed between LangGraph agents.

    Each agent reads the information it needs and adds its
    results to this shared state.
    """

    # Input provided by the user
    project_details: Dict[str, Any]

    # Output from the screening agent
    screening_result: Dict[str, Any]

    # Regulatory information retrieved through the RAG system
    regulatory_context: List[Dict[str, Any]]

    # Output from the risk assessment agent
    risk_assessment: Dict[str, Any]

    # Final report generated by the report agent
    final_report: Dict[str, Any]

    # Workflow tracking
    current_step: str

    # Errors encountered during agent execution
    errors: List[str]
